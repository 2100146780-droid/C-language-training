/* ---- 头文件 ----
 * #include 的意思：把别人写好的工具箱搬进来。
 * stdio.h  → 标准输入输出：printf、scanf 住在这里（standard I/O）
 * stdlib.h → 标准工具库：rand、srand 住在这里（standard library）
 * time.h   → 时间函数：time 住在这里
 * 忘了包含会怎样？gcc 报 implicit declaration of function 'xxx'，
 * 报错下面还会好心告诉你该加哪个头文件。 */
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

/* ---- 程序入口 ----
 * int main(void)：每个 C 程序都从这里开始执行，有且只有一个。
 * 前面的 int 表示程序结束后会返回一个整数给操作系统（return 0）。
 * (void) 表示"不接收任何参数"。 */
int main(void)
{
    /* ---- 变量声明 ----
     * C 是强类型语言：用变量前必须先声明类型。
     * int   → 整数（4字节，能存约 ±21亿）
     * num       ：用户猜的数
     * times     ：猜了几次，= 0 是"初始化"，不初始化它的值是随机的垃圾值！
     * fixed_num ：电脑心里那个数 */
    int num, times = 0, fixed_num;

    /* ---- 随机数三件套（本程序最核心的知识点）----
     * 计算机不会真随机，它内置一张超长的"乱序数字表"。
     * rand()  ：从表里读下一个数（每调一次往后挪一格）
     * srand(x)：决定从表的哪个位置开始读（种子）
     * time(NULL)：当前时间（1970年至今的秒数），每秒都不同
     * 组合起来：用当前时间当种子 → 每次运行起点不同 → 看起来随机
     *
     * (unsigned)：强制类型转换。time 返回的类型和 srand 要的不一样，
     *             转一下才能喂进去。
     *
     * ★ srand 必须放在循环外、只调一次！
     *   放循环里：一秒内种子不变 → 每次读到同一个数 → 不随机了。
     *
     * rand() % 100 + 1：表里的数几千几万大，%100 取余折叠到 0~99，
     *                   再 +1 变成 1~100。比如 18467 % 100 = 67。
     *                   "大数折叠进小区间"是嵌入式里的常用手法。 */
    srand((unsigned)time(NULL));
    fixed_num = rand() % 100 + 1;

    /* ---- printf 两个坑 ----
     * \n 是换行（反斜杠）。写成 /n 编译器不报错，运行时原样打印，
     * 属于最阴的 bug。
     * %d 是"占位符"：打印时被后面变量的值替换掉。
     * printf("猜了 %d 次\n", times) → 猜了 3 次 */
    printf("I have picked a number between 1 and 100, can you guess it?\n");

    /* ---- while(1)：死循环 ----
     * 条件永远是真 → 永远循环。游戏、单片机主程序都这么写。
     * 单片机里的 while(1) 就是让程序永远运转。
     * 跳出去的手段：break。 */
    while (1)
    {
        printf("you guess: ");

        /* ---- scanf：读输入 ----
         * scanf("%d", &num) 等着用户敲一个整数，存进 num。
         * ★ num 前面的 & 不能丢！
         *   & 的意思是"num 的地址"，scanf 必须知道把数放到哪去。
         *   漏了 & 程序会崩溃 —— 这是你和指针的第一次照面，
         *   指针 = 存地址的变量，第三周重点讲。 */
        scanf("%d", &num);

        /* 需求：输入 0 直接退出。
         * 放在 times++ 之前 —— 退出那一下不算一次猜测。 */
        if (num == 0)
            break;

        times++;    /* 等价于 times = times + 1，自增 */

        /* ---- if / else if / else 接力 ----
         * 三种情况互斥，从上往下挨个检查，命中一个就跳过其余。
         * 注意：每个 else if 必须跟在上一个 } 的后面，平级接力，
         * 不能塞进别人的大括号里（昨晚的编译错误就是这来的）。
         * 其实最后一个可以只写 else —— 不是大了也不是小了，
         * 那就只剩猜中，不用再查条件。 */
        if (num > fixed_num)
        {
            printf("too big \n");
        }
        else if (num < fixed_num)
        {
            printf("too small \n");
        }
        else    /* 能走到这，只剩猜中这一种可能 */
        {
            printf("you are right! you have guessed %d times\n", times);
            break;   /* 跳出 while(1)，去执行 return 0 */
        }
    }

    /* return 0：告诉操作系统"程序正常结束"。 */
    return 0;
}

