#include <stdio.h>

/* ============================================================
 * 今晚的目标只有两个空要填，其他都不用动。
 * 一个字节 = 8 盏灯：某位是 1 = 亮，是 0 = 灭。
 * ============================================================ */

/* 把 8 盏灯打印成一行，比如 0b00010000 打印出 ___X____ */
void show_leds(unsigned char leds)
{
    /* i 从最高位(7)数到最低位(0) */
    for (int i = 7; i >= 0; i--) {
        /* (leds >> i) & 1 的结果就是第 i 位的值：1 或者 0
         *
         * ★ 空一：在这里打印这一位
         *   是 1 就打印 'X'，是 0 就打印 '_'
         *   抄这行（把 ??? 换成正确的字符）：
         *   printf("%c", ((leds >> i) & 1) == 1 ? '?' : '?');
         */
        printf("%c", ((leds >> i) & 1) == 1 ? 'X' : '_');   /* ← 把两个 ? 改成 'X' 和 '_' */
    }
    printf("\n");
}

