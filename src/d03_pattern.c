/*
    直角三角形
    外层循环控制行数，内层循环控制每行打印星号的数量
    效果：
    *
    **
    ***
    ****
    *****
*/
#include<stdio.h>

int main(void)
{
    int a,b;
    // a 代表当前是第几行，一共打印5行，从第1行到第5行
    for(a=1;a<=5;a++)
    {
        // b 控制这一行要打印多少个*，第a行就打印a个星号
        for(b=1;b<=a;b++)
        {
            printf("*"); // 打印一个星号，不换行
        }
        
        printf("\n");   // 一行的星号打完，换行，准备下一行
    }

    return 0;
}
